def clean(s):
    s = re.sub(r"〖[@=;&%~+!?]?", "", s or "")
    s = s.replace("〗", "").replace("〖", "")
    s = s.replace("•", "").replace("^", "")
    s = re.sub(r"\s+", "", s)
    # ASCII 双引号 → 中文引号（成对），避免破坏 TS 字符串
    s = re.sub(r'"([^"]*)"', r"“\1”", s)
    s = s.replace('"', "”")
    return s.strip()

def trim(s, limit=78):
    s = clean(s)
    if len(s) <= limit:
        return s
    for mark in ("。", "；"):
        idx = s.rfind(mark, 0, limit + 1)
        if idx >= 40:
            return s[: idx + 1]
    for mark in ("，", "、"):
        idx = s.rfind(mark, 0, limit + 1)
        if idx >= 40:
            return s[:idx] + "。"
    return s[:limit] + "。"

