def chapter_name(ch):
    return ch.split("_")[1]

def suffix(r):
    name = chapter_name(r["chapter"])
    if r["dynasty"] in ("夏", "商"):
        return f"（据《史记·{name}》；年代依夏商周断代工程推定）"
    return f"（据《史记·{name}》）"

n = {}
ts = []
review = []
for r in rows:
    dyn = r["dynasty"]
    n[dyn] = n.get(dyn, 0) + 1
    eid = f"{PREFIX[dyn]}-{n[dyn]:02d}"
    body = OVERRIDE.get(r["event_id"]) or trim(r["description"])
    desc = clean(body) + suffix(r)
    ts.append(
        "  {\n"
        f'    id: "{eid}",\n'
        f'    title: "{r["title"]}",\n'
        f'    dynasty: "{dyn}",\n'
        f'    year: {r["year"]},\n'
        f'    description:\n      "{desc}",\n'
        "  },"
    )
    review.append(f"{eid} | {dyn} {r['year']} | {r['title']}\n    {desc}")

open(os.path.join(TMP, "ts_block.txt"), "w", encoding="utf-8").write("\n".join(ts))
