def dynasty_of(e):
    y, ch = e.get("year"), e.get("chapter", "")[:3]
    name = e.get("event_name") or ""
    if y is None: return None
    # 边界例外：夏亡（前1600）归夏；商兴（伊尹辅汤/汤征葛伯/汤修德，前1617-前1605）归商
    if "桀走鸣条" in name or "桀败鸣条" in name: return "夏"
    if any(k in name for k in ("伊尹辅汤", "汤征葛伯", "汤修德", "网开三面")): return "商"
    if ch == "002" and -2100 <= y <= -1601: return "夏"
    if -2070 <= y <= -1601: return "夏"
    if -1600 <= y <= -1047: return "商"
    if -1046 <= y <= -771: return "西周"
    if -770 <= y <= -476: return "春秋"
    if -475 <= y <= -222: return "战国"
    return None

