# 同名多源时的指定来源章节（默认取描述最长者）
PREFER_CHAPTER = {
    ("战国", -225, "秦灭魏"): "015",
    ("战国", -222, "秦灭燕"): "034",
}

rows, problems = [], []
for dyn, year, key, title in SEL:
    cands = [e for e in events if e["dynasty"] == dyn and e["year"] == year and key in (e.get("event_name") or "")]
    if not cands:
        problems.append(("NOT_FOUND", dyn, year, key, title))
        continue
    pref = PREFER_CHAPTER.get((dyn, year, key))
    if pref:
        cands = [e for e in cands if e["chapter"][:3] == pref] or cands
    # 同名多源时取描述最长的（信息最全）
    best = max(cands, key=lambda e: len(e.get("description") or ""))
    rows.append({
        "dynasty": dyn, "year": year, "title": title,
        "source_name": best["event_name"], "event_id": best["event_id"],
        "chapter": best["chapter"], "precision": best["precision"],
        "description": best.get("description", ""), "quote": best.get("source_text", ""),
        "para": best.get("paragraph", ""), "persons": best.get("persons", ""),
    })

print("selected:", len(rows), "problems:", len(problems))
for p in problems: print("  !!", p)

# 按朝代顺序 + 年份稳定排序（同年内保持选目顺序）
DORDER = {"夏": 0, "商": 1, "西周": 2, "春秋": 3, "战国": 4}
rows.sort(key=lambda r: (DORDER[r["dynasty"]], r["year"]))

cnt = collections.Counter(r["dynasty"] for r in rows)
print("per dynasty:", dict(cnt))
# 同年重复检查
dup = [k for k, v in collections.Counter((r["dynasty"], r["year"], r["title"]) for r in rows).items() if v > 1]
print("dup title+year:", dup)
# 同朝代同年的多事件
for dyn in ["夏", "商", "西周", "春秋", "战国"]:
    years = [r["year"] for r in rows if r["dynasty"] == dyn]
    if len(years) != len(set(years)):
        print(dyn, "同年多事件:", [y for y in set(years) if years.count(y) > 1])

